// TestYAML_PortContractIsUniform pins the #550 contract across every target:
// the port argument must always be rendered with the '=' carried by the name,
// and a bare "-port" must never appear as an arg.
func TestYAML_PortContractIsUniform(t *testing.T) {
	variants := map[string]Config{
		"container": {Args: []Arg{PortArg("{{.ContainerPort}}")}},
		"anywhere":  {Args: []Arg{PortArg("7777")}},
		"ec2":       {Args: []Arg{PortArg("{{.GamePort}}")}},
	}

	for name, cfg := range variants {
		doc := cfg.YAML()
		if !strings.Contains(doc, `arg: "-port="`) {
			t.Errorf("%s: port arg missing '-port=':\n%s", name, doc)
		}
		for _, line := range strings.Split(doc, "\n") {
			if strings.Contains(line, `"arg: "-port""`) || strings.Contains(line, `- arg: "-port"`) {
				t.Errorf("%s: bare -port arg would be ignored by UE:\n%s", name, doc)
			}
		}
	}
}

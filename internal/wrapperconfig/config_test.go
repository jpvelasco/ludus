func TestYAML_Container(t *testing.T) {
	got := Config{
		GamePort:       7777,
		ExecutablePath: "./Lyra/Binaries/Linux/LyraServer",
		Args: []Arg{
			{Name: "Lyra"},
			PortArg("{{.ContainerPort}}"),
			{Name: "-log"},
		},
	}.YAML()

	want := `# Generated by ludus
log-config:
  wrapper-log-level: info

ports:
  gamePort: 7777

game-server-details:
  executable-file-path: "./Lyra/Binaries/Linux/LyraServer"
  game-server-args:
    - arg: "Lyra"
      pos: 0
    - arg: "-port="
      val: "{{.ContainerPort}}"
      pos: 1
    - arg: "-log"
      pos: 2
`
	if got != want {
		t.Errorf("container config mismatch:\ngot:\n%s\nwant:\n%s", got, want)
	}
}

